#include <unistd.h>

void	ft_putnbr(int nb)
{
	long	num;

	num = nb;
	if (num < 0)
	{
		write(1, "-", 1);
		num = -num;
	}
	if (num < 10)
	{
		write(1, &"0123456789"[num], 1);
	}
	else
	{
		ft_putnbr(num / 10);
		write(1, &"0123456789"[num % 10], 1);
	}
}
